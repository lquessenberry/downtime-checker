"""Write docs/CESIUM_MAP.md — the living rebuild plan."""

from __future__ import annotations

from pathlib import Path

from engines import Engine
from knowledge import GSA_LAYERS, MODULES, WGS84_RADII_M, by_priority
from policy import ALLOWED_TARGETS


def render(
    *,
    engine: Engine,
    mcp_summary: str,
    cesium_inv: dict | None,
    rust_files: list[str],
) -> str:
    rows = []
    for mod in by_priority():
        rows.append(
            f"| `{mod['id']}` | {', '.join(f'`{c}`' for c in mod['cesium'][:4])} "
            f"| `{mod['rust']}` | {mod['status']} | P{mod['priority']} |"
        )
    layer_rows = [
        f"| `{lid}` | {title} | {status} |" for lid, title, status in GSA_LAYERS
    ]
    inv_block = "_No CesiumGS/cesium checkout on disk. Clone it, or pass `--cesium-src`._"
    if cesium_inv:
        hits = "\n".join(f"- `{h}`" for h in cesium_inv.get("symbol_hits", [])[:40]) or "_none_"
        inv_block = (
            f"- Root: `{cesium_inv['root']}`\n"
            f"- JS files: {cesium_inv['js_files']}\n"
            f"- Core/Scene/Renderer/Workers: "
            f"{cesium_inv['core_present']}/"
            f"{cesium_inv['scene_present']}/"
            f"{cesium_inv['renderer_present']}/"
            f"{cesium_inv['workers_present']}\n\n"
            f"Symbol hits:\n{hits}\n"
        )
    rust_block = "\n".join(f"- `{p}`" for p in rust_files) or "_`--emit-rust` not used this run._"
    allowed = "\n".join(
        f"- **{k}** ({v['license']}) — {v['repo']} — {v['notes']}"
        for k, v in ALLOWED_TARGETS.items()
    )
    return f"""# Cesium → globe-native map

Generated by `scripts/globe-re`. This is a **rebuild plan**, not a decompile of
minified `Cesium.js`. CesiumJS is Apache-2.0; we read `Source/` and write new
Rust under `rust/crates/globe-native/src/engine/`.

## Engine this machine picked

- **{engine.title}** (`{engine.id}`), cost: {engine.cost}
- Present: {', '.join(engine.found) if engine.found else 'no binary on PATH (source-map fallback)'}
- MCP: {engine.mcp}
- When: {engine.when}

{mcp_summary}

## WGS84

Cesium `Ellipsoid.WGS84` radii (meters): `{list(WGS84_RADII_M)}`.

Native wgpu frame is **not** Cesium ECEF:

| Axis | Cesium ECEF | globe-native unit sphere |
| --- | --- | --- |
| +X | (0°N, 0°E) | (0°N, 0°E) |
| +Y | (0°N, 90°E) | North pole |
| +Z | North pole | (0°N, 90°W) |

`engine::ellipsoid::Ellipsoid::cartographic_to_native_unit` applies
`[x, z, -y]` then normalizes.

## Module map

| id | Cesium types | Rust destination | status | pri |
| --- | --- | --- | --- | --- |
{chr(10).join(rows)}

## Global Status layers

| id | name | native |
| --- | --- | --- |
{chr(10).join(layer_rows)}

## Cesium source inventory

{inv_block}

## Files written this run

{rust_block}

## Allowed targets

{allowed}

Refused: Google Earth, ArcGIS Pro, Apple Maps, Bing, Mapbox GL JS.
osgEarth is LGPL — read, do not statically link.

## How an agent should drive this

1. `python3 scripts/globe-re/globe_re.py engines`
2. Start GhidraMCP (or r2 / IDA / Binja) if the target is native/WASM.
3. `python3 scripts/globe-re/globe_re.py probe`
4. One function at a time: `python3 scripts/globe-re/globe_re.py follow --function NAME`
5. Fill the matching file under `src/engine/`. Do not dump the whole binary into one prompt.
6. Agents read and locate well and hold a whole program poorly. Stay on one xref chain.

## Succeed-Cesium bar

See [rust-native.md](rust-native.md). Native wins when XYZ, terrain, 2D, live
layers, grid spiderweb, and the in-process poller match the web globe.

Do not port Cesium ion.
"""


def write(path: Path, **kwargs) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(**kwargs), encoding="utf-8")
    return path
