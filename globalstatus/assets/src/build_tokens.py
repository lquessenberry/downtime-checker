#!/usr/bin/env python3
"""Build Global Status design tokens: tokens/tokens.json (DTCG) -> CSS, Rust (egui), TS, flat JSON, contrast report."""
import json, re, os
from contrast import ratio
ROOT = os.path.dirname(os.path.abspath(__file__)) + "/../tokens"
src = json.load(open(f"{ROOT}/tokens.json"))
os.makedirs(f"{ROOT}/dist", exist_ok=True)

flat = {}   # "color.base.night.950" -> {"type":..,"value":..,"desc":..}
def walk(node, path, inherited=None):
    t = node.get("$type", inherited)
    if "$value" in node:
        flat[".".join(path)] = {"type": t, "value": node["$value"], "desc": node.get("$description","")}; return
    for k, v in node.items():
        if k.startswith("$"): continue
        walk(v, path+[k], t)
walk(src, [])
REF = re.compile(r"^\{([^}]+)\}$")
def resolve(v, seen=()):
    if isinstance(v, str) and REF.match(v):
        p = REF.match(v).group(1); return resolve(flat[p]["value"], seen+(p,))
    if isinstance(v, dict): return {k: resolve(x) for k,x in v.items()}
    if isinstance(v, list): return [resolve(x) for x in v]
    return v
R = {k: {**t, "value": resolve(t["value"])} for k,t in flat.items()}

def css_val(t):
    v=t["value"]; ty=t["type"]
    if ty=="fontFamily": return ", ".join(f'"{f}"' if " " in f else f for f in v)
    if ty=="cubicBezier": return "cubic-bezier(%s)" % ", ".join(str(x) for x in v)
    if ty=="shadow": return f'{v["offsetX"]} {v["offsetY"]} {v["blur"]} {v["spread"]} {v["color"]}'
    if ty=="typography": return None
    return str(v)
def cssname(k): return "--gs-" + k.replace(".", "-").replace("_",".")
# ---- CSS: every token as a primitive var, plus theme-switching semantic aliases
lines = ["/* Generated by build_tokens.py from tokens.json. Do not edit by hand. */", ":root {"]
for k,t in R.items():
    v = css_val(t)
    if v is not None: lines.append(f"  {cssname(k)}: {v};")
for k,t in R.items():
    if t["type"]=="typography":
        v=t["value"]; fam=", ".join(f'"{f}"' if " " in f else f for f in v["fontFamily"])
        lines.append(f'  {cssname(k)}: {v["fontWeight"]} {v["fontSize"]}/{v["lineHeight"]} {fam};')
        lines.append(f'  {cssname(k)}-tracking: {v["letterSpacing"]};')
lines.append("}")
def theme_block(sel, mode):
    out=[f"{sel} {{", f"  color-scheme: {mode};"]
    for k in R:
        for pre in (f"color.{mode}.", f"color.status.{mode}.", f"color.severity.{mode}."):
            if k.startswith(pre):
                tail = k[len(f"color.{mode}."):] if pre==f"color.{mode}." else k.replace(f".{mode}","")[len("color."):]
                out.append(f"  --gs-{tail.replace('.','-')}: var({cssname(k)});")
    out.append("}"); return out
lines += theme_block(':root, [data-theme="dark"]', "dark")
lines += theme_block('[data-theme="light"]', "light")
lines += ["@media (prefers-color-scheme: light) {"] + ["  "+l for l in theme_block(':root:not([data-theme="dark"])', "light")] + ["}"]
lines += ["@media (prefers-reduced-motion: reduce) {", "  :root { --gs-motion-duration-pulse: 0ms; --gs-motion-duration-camera: 0ms; --gs-motion-duration-slow: 0ms; --gs-motion-duration-base: 0ms; }", "}"]
open(f"{ROOT}/dist/tokens.css","w").write("\n".join(lines)+"\n")

# ---- Flat JSON + TS
flat_out = {k: t["value"] for k,t in R.items()}
json.dump(flat_out, open(f"{ROOT}/dist/tokens.flat.json","w"), indent=2)
def nest(d):
    out={}
    for k,v in d.items():
        cur=out; parts=k.split(".")
        for p in parts[:-1]: cur=cur.setdefault(p,{})
        cur[parts[-1]]=v
    return out
ts = "// Generated by build_tokens.py from tokens.json. Do not edit by hand.\n"
ts += "export const tokens = " + json.dumps(nest(flat_out), indent=2) + " as const;\n\n"
ts += "export type Tokens = typeof tokens;\nexport type TokenPath = " + " | ".join(json.dumps(k) for k in flat_out) + ";\n"
ts += "export const flat: Record<TokenPath, unknown> = " + json.dumps(flat_out, indent=2) + ";\n"
ts += "export const cssVar = (path: TokenPath): string => `var(--gs-${path.replace(/\\./g, '-').replace(/_/g, '.')})`;\n"
open(f"{ROOT}/dist/tokens.ts","w").write(ts)

# ---- Rust (egui)
def rgba(v):
    v=v.strip()
    if v.startswith("#"):
        h=v[1:]; a=int(h[6:8],16) if len(h)==8 else 255
        return int(h[0:2],16),int(h[2:4],16),int(h[4:6],16),a
    m=re.match(r"rgba?\(([^)]+)\)", v); p=[x.strip() for x in m.group(1).split(",")]
    return int(p[0]),int(p[1]),int(p[2]), round(float(p[3])*255) if len(p)>3 else 255
def rsname(k, strip): 
    n=k[len(strip):] if k.startswith(strip) else k
    n=re.sub(r"[^A-Za-z0-9]+","_",re.sub(r"([a-z])([A-Z0-9])", r"\1_\2", n)).upper().strip("_")
    return ("N"+n) if n[0].isdigit() else n
rs = ["//! Generated by build_tokens.py from tokens.json. Do not edit by hand.",
      "//! Global Status design tokens for the native Rust apps (wgpu + egui).",
      "#![allow(dead_code)]", "",
      "/// Straight (non-premultiplied) sRGB + alpha, usable from wgpu shaders/uniforms.",
      "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
      "pub struct Rgba8(pub u8, pub u8, pub u8, pub u8);",
      "impl Rgba8 {",
      "    /// Linear-ish f32 array in 0..1 (sRGB encoded), for vertex colors / uniforms.",
      "    pub const fn to_array(self) -> [u8; 4] { [self.0, self.1, self.2, self.3] }",
      "    pub fn to_f32(self) -> [f32; 4] { [self.0 as f32 / 255.0, self.1 as f32 / 255.0, self.2 as f32 / 255.0, self.3 as f32 / 255.0] }",
      "}",
      "#[cfg(feature = \"egui\")]",
      "impl From<Rgba8> for egui::Color32 {",
      "    fn from(c: Rgba8) -> Self { egui::Color32::from_rgba_unmultiplied(c.0, c.1, c.2, c.3) }",
      "}", ""]
groups = {"color":[],"dim":[],"num":[],"dur":[]}
rs.append("pub mod color {\n    use super::Rgba8;")
for k,t in R.items():
    if t["type"]=="color":
        r,g,b,a = rgba(t["value"])
        doc = f"    /// `{k}` = {t['value']}" + (f" — {t['desc']}" if t["desc"] else "")
        rs += [doc, f"    pub const {rsname(k,'color.')}: Rgba8 = Rgba8({r}, {g}, {b}, {a});"]
rs.append("}\n")
rs.append("/// Ready-to-use egui colors (premultiplied, const). Enable the `egui` feature.\n#[cfg(feature = \"egui\")]\npub mod color32 {\n    use egui::Color32;")
for k,t in R.items():
    if t["type"]=="color":
        r,g,b,a = rgba(t["value"]); pm=lambda x: round(x*a/255)
        rs.append(f"    pub const {rsname(k,'color.')}: Color32 = Color32::from_rgba_premultiplied({pm(r)}, {pm(g)}, {pm(b)}, {a});")
rs.append("}\n")
rs.append("/// Sizes in logical points (egui units).\npub mod size {")
for k,t in R.items():
    if t["type"]=="dimension" and str(t["value"]).endswith("px"):
        rs.append(f"    pub const {rsname(k,'')}: f32 = {float(t['value'][:-2])};")
rs.append("}\n")
rs.append("pub mod number {")
for k,t in R.items():
    if t["type"]=="number": rs.append(f"    pub const {rsname(k,'')}: f32 = {float(t['value'])};")
rs.append("}\n")
rs.append("/// Durations in milliseconds.\npub mod motion {")
for k,t in R.items():
    if t["type"]=="duration": rs.append(f"    pub const {rsname(k,'motion.duration.')}_MS: u32 = {int(t['value'][:-2])};")
    if t["type"]=="cubicBezier": rs.append(f"    pub const {rsname(k,'motion.easing.')}_BEZIER: [f32; 4] = [{', '.join(str(float(x)) for x in t['value'])}];")
rs.append("}\n")
rs.append("pub mod font {")
for k,t in R.items():
    if t["type"]=="fontFamily": rs.append(f"    pub const {rsname(k,'font.family.')}: &[&str] = &[{', '.join(json.dumps(x) for x in t['value'])}];")
rs.append("}")
open(f"{ROOT}/dist/tokens.rs","w").write("\n".join(rs)+"\n")

# ---- Contrast report
def hexof(v):
    r,g,b,a = rgba(v); return "#%02x%02x%02x" % (r,g,b)
pairs = []
for mode in ("dark","light"):
    for bgk in ("canvas","surface","raised"):
        bg = hexof(R[f"color.{mode}.bg.{bgk}"]["value"])
        for grp in ("text","status","severity"):
            pre = f"color.{mode}.text." if grp=="text" else f"color.{grp}.{mode}."
            for k,t in R.items():
                if k.startswith(pre) and not k.endswith("onFill"):
                    pairs.append((mode, bgk, bg, k, hexof(t["value"]), ratio(hexof(t["value"]), bg)))
    # on-fill text on status chips
    onfill = hexof(R[f"color.{mode}.text.onFill"]["value"])
    for k,t in R.items():
        if k.startswith(f"color.status.{mode}.") or k.startswith(f"color.severity.{mode}."):
            pairs.append((mode, "chip:"+k.split(".")[-1], hexof(t["value"]), f"color.{mode}.text.onFill", onfill, ratio(onfill, hexof(t["value"]))))
for k,t in R.items():
    if k.startswith("color.layer.") or k.startswith("color.layerOnLight."):
        if k.startswith("color.layer."): pairs.append(("dark","canvas","#070b10",k,hexof(t["value"]),ratio(hexof(t["value"]),"#070b10")))
        else: pairs.append(("light","surface","#ffffff",k,hexof(t["value"]),ratio(hexof(t["value"]),"#ffffff")))
def grade(r): return "AAA" if r>=7 else "AA" if r>=4.5 else "AA-large/UI" if r>=3 else "FAIL"
md = ["# Global Status contrast report (WCAG 2.x)", "", "| Mode | Background | Foreground token | FG | BG | Ratio | Grade |","|---|---|---|---|---|---|---|"]
for m,b,bg,k,fg,r in pairs: md.append(f"| {m} | {b} | `{k}` | {fg} | {bg} | {r:.2f} | {grade(r)} |")
open(f"{ROOT}/contrast-report.md","w").write("\n".join(md)+"\n")
json.dump([dict(mode=m,bg_name=b,bg=bg,token=k,fg=fg,ratio=round(r,2),grade=grade(r)) for m,b,bg,k,fg,r in pairs], open(f"{ROOT}/contrast.json","w"), indent=1)
fails=[p for p in pairs if p[5]<4.5]
print(f"{len(R)} tokens; {len(pairs)} contrast pairs; text/status pairs under 4.5: {len(fails)}")
for p in fails: print("  ", p[0],p[1],p[3],p[4],round(p[5],2))
